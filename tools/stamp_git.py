#!/usr/bin/env python3
"""
stamp_git.py - write Core/Inc/git_version.h with the current git commit.

Run automatically as a STM32CubeIDE pre-build step (see HOW_TO_APPLY.txt):
    python "${ProjDirPath}/tools/stamp_git.py"

The header defines
    FW_GIT_COMMIT  short commit hash, e.g. "903bd20"   ("unknown" if git fails)
    FW_GIT_DIRTY   1 if tracked files differ from that commit, else 0
and is printed in every run's META line, so each log can be traced to the
exact source it was built from. A dirty build means "commit X plus local
changes": commit first, then build, for fully traceable results.

git_version.h is listed in .gitignore, so writing it never makes the tree
dirty. It is only rewritten when the content changes, to avoid needless
recompilation.
"""
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "Core", "Inc", "git_version.h")


def git(*args):
    return subprocess.run(["git", "-C", ROOT, *args], capture_output=True, text=True,
                          timeout=10).stdout.strip()


try:
    commit = git("rev-parse", "--short", "HEAD") or "unknown"
    dirty = 1 if git("status", "--porcelain", "--untracked-files=no") else 0
except Exception:                      # git missing or not a repository
    commit, dirty = "unknown", 0

text = ("/* Generated by tools/stamp_git.py before every build - do not edit. */\n"
        "#ifndef GIT_VERSION_H\n#define GIT_VERSION_H\n"
        f'#define FW_GIT_COMMIT "{commit}"\n'
        f"#define FW_GIT_DIRTY  {dirty}\n"
        "#endif\n")

old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
if old != text:
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
print(f"stamp_git: {commit}{' (dirty)' if dirty else ''}")
sys.exit(0)
